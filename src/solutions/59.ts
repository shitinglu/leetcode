/**
 * 452. 用最少数量的箭引爆气球
 * 题目链接: https://leetcode.cn/problems/minimum-number-of-arrows-to-burst-balloons/
 *
 * 有一些球形气球贴在一堵墙上。每个气球都标有一个不同的整数。
 * 你可以沿着 x 轴从不同点射出箭。一支箭可以沿着 x 轴的任何位置向上射出。
 * 如果箭射出的位置 x 正好在气球的范围 [x_start, x_end] 内，则该气球会被引爆。
 * 给你一个数组 points ，其中 points[i] = [x_start, x_end] ，返回引爆所有气球所需的最小弓箭数。
 *
 * 示例 1：
 * 输入：points = [[10,16],[2,8],[1,6],[7,12]]
 * 输出：2
 * 解释：气球可以用2支箭来爆破:
 * -在x = 6处射出箭，击破气球[2,8]和[1,6]。
 * -在x = 11处射出箭，击破气球[10,16]和[7,12]。
 *
 * 示例 2：
 * 输入：points = [[1,2],[3,4],[5,6],[7,8]]
 * 输出：4
 * 解释：每个气球需要射出一支箭，共需要4支箭。
 *
 * 示例 3：
 * 输入：points = [[1,2],[2,3],[3,4],[4,5]]
 * 输出：2
 * 解释：气球可以用2支箭来爆破:
 * - 在x = 2处发射，击破气球[1,2]和[2,3]。
 * - 在x = 4处发射，击破气球[3,4]和[4,5]。
 *
 * 提示：
 * - 1 <= points.length <= 10^5
 * - points[i].length == 2
 * - -2^31 <= x_start < x_end <= 2^31 - 1
 */

/**
 * 问题: 452. 用最少数量的箭引爆气球
 *
 * 解题思路：
 * 1. 问题本质
 * - 在一维空间中有多个区间[x_start, x_end]，每个区间代表一个气球的范围
 * - 一支箭可以引爆它射出位置x所覆盖的所有气球
 * - 求引爆所有气球所需的最少箭数
 * - 本质是求解最少数量的点，使得每个区间至少包含一个点
 *
 * 2. 解决方案
 * A. 贪心算法
 * - 按照区间的结束位置进行排序
 * - 尽可能将箭射在重叠区间的最右端（当前处理区间的结束位置）
 * - 这样可以保证一支箭能引爆尽可能多的气球
 *
 * 3. 具体执行流程
 * 以例子 [[10,16],[2,8],[1,6],[7,12]] 为例:
 * - 排序后: [[1,6], [2,8], [7,12], [10,16]]
 * - 第一支箭放在x=6（第一个气球的结束位置）
 *   - 引爆[1,6]、[2,8]（因为6在这两个区间内）
 * - 检查[7,12]，发现7>6，需要新箭
 * - 第二支箭放在x=12（当前气球的结束位置）
 *   - 引爆[7,12]、[10,16]（因为12在这两个区间内）
 * - 所有气球都被引爆，总共需要2支箭
 *
 * 4. 关键点
 * - 贪心选择：总是将箭射在当前处理区间的最右端
 * - 排序策略：按照区间的结束位置排序至关重要
 * - 重叠判断：当前气球的起始位置大于箭的位置时，说明需要新箭
 * - 特殊情况：当输入为空时，返回0
 *
 * 5. 复杂度分析
 * - 时间复杂度: O(n log n)，主要是排序的开销
 * - 空间复杂度: O(1)，只需要常数额外空间（不考虑排序的栈空间）
 *
 * 6. 方法选择
 * - 贪心算法是解决此类区间问题的最佳选择
 * - 动态规划也可以解决，但会增加不必要的复杂度
 * - 此问题可以转化为"区间覆盖问题"，贪心策略已被证明是最优的
 */

export function findMinArrowShots(points: number[][]): number {
  if (points.length === 0) return 0;
  // 按结束位置排序
  points.sort((a, b) => a[1] - b[1]);

  let arrowPos = points[0][1]; // 第一支箭射在第一个气球的结束位置
  let arrowCount = 1;

  // 遍历剩余的气球
  for (let i = 1; i < points.length; i++) {
    // 如果当前气球的开始位置大于箭的位置，说明当前箭无法引爆这个气球，需要增加新箭
    if (points[i][0] > arrowPos) {
      arrowCount++;
      arrowPos = points[i][1]; // 新箭射在当前气球的结束位置
    }
  }

  // 实现代码
  return arrowCount;
}

export default {
  run: () => {
    const examples = [
      {
        input: [
          [10, 16],
          [2, 8],
          [1, 6],
          [7, 12],
        ],
        output: 2,
      },
      {
        input: [
          [1, 2],
          [3, 4],
          [5, 6],
          [7, 8],
        ],
        output: 4,
      },
      {
        input: [
          [1, 2],
          [2, 3],
          [3, 4],
          [4, 5],
        ],
        output: 2,
      },
    ];

    for (const example of examples) {
      const result = findMinArrowShots(example.input);
      console.log(`输入: points = ${JSON.stringify(example.input)}, 输出: ${result}`);
      console.log(`测试结果: ${result === example.output ? '通过' : '失败'}`);
    }
  },
};
