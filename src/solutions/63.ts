/**
 * 1466. 重新规划路线
 * 题目链接: https://leetcode.cn/problems/reorder-routes-to-make-all-paths-lead-to-the-city-zero/
 *
 * n 座城市，从 0 到 n-1 编号，其间共有 n-1 条道路。因此，所有城市形成了一个简单无环连通图。
 * 城市图由数组 edges 组成，其中 edges[i] = [fromi, toi] 表示城市 fromi 和 toi 之间有一条有向边。
 * 题目保证任意城市之间只有一条路径。
 *
 * 示例：
 * 输入：n = 6, connections = [[0,1],[1,3],[2,3],[4,0],[4,5]]
 * 输出：3
 * 解释：更改以红色显示的路线方向，使得每个城市都可以到达城市 0。
 *
 * 示例 2：
 * 输入：n = 5, connections = [[1,0],[1,2],[3,2],[3,4]]
 * 输出：2
 * 解释：更改以红色显示的路线方向，使得每个城市都可以到达城市 0。
 *
 * 示例 3：
 * 输入：n = 3, connections = [[1,0],[2,0]]
 * 输出：0
 *
 * 提示：
 * - 2 <= n <= 5 * 10^4
 * - connections.length == n-1
 * - connections[i].length == 2
 * - 0 <= fromi, toi <= n-1
 * - fromi != toi
 */

/**
 * 解题思路：
 * 1. 问题本质
 * - 在给定的有向图中，需要将一些边反向，使得从任意节点都能到达节点0
 * - 图是树形结构（n个节点，n - 1条边）
 * - 需要计算最少需要反转多少条边
 *
 * 2. 解决方案
 * A.无向图构建 + DFS / BFS
 * - 将有向边视为双向边，但标记原始方向
 * - 从节点0开始，进行深度优先搜索或广度优先搜索
 * - 遍历过程中，如果从父节点到子节点的边方向与原始方向一致，则需要反转
 *
 * 3. 具体执行流程(以DFS为例)：
 * 以 connections = [[0, 1], [1, 3], [2, 3], [4, 0], [4, 5]] 为例：
 * - 第一步：构建邻接表
 * - 城市0: [(1, 1), (4, 0)]  // (1,1)表示原方向是0->1，(4,0)表示原方向是4->0
 * - 城市1: [(0, 0), (3, 1)]  // 0表示不需要翻转，1表示需要翻转
 * - 城市2: [(3, 1)]
 * - 城市3: [(1, 0), (2, 0)]
 * - 城市4: [(0, 1), (5, 1)]
 * - 城市5: [(4, 0)]
 * - 第二步：从城市0开始DFS
 * - 访问城市1：边(0, 1)与原方向一致，需要翻转，计数 + 1=1
 * - 访问城市3：边(1, 3)与原方向一致，需要翻转，计数 + 1=2
 * - 访问城市2：边(3, 2)与原方向相反，不需要翻转
 * - 访问城市4：边(0, 4)与原方向相反，不需要翻转
 * - 访问城市5：边(4, 5)与原方向一致，需要翻转，计数 + 1=3
 * - 返回匹配总数：3
 *
 * 4. 代码的详细执行过程
 * - 构建邻接表：
 * - 初始化一个大小为n的数组，每个元素是一个空数组
 * - 遍历connections数组，对于每条边[from, to]：
 * - 在graph[from]中添加[to, 1]，表示从from到to的原始方向，需要翻转
 * - 在graph[to]中添加[from, 0]，表示从to到from的反向连接，不需要翻转
 *
 * - DFS遍历过程（以示例1为例）：
 * - 初始化visited数组为全false，count为0
 * - 调用dfs(0)开始遍历：
 * - 标记城市0为已访问
 * - 遍历城市0的邻居：城市1和城市4
 * - 城市1未访问，检查边(0, 1)的标记为1，表示需要翻转，count + 1=1
 * - 递归调用dfs(1)：
 * - 标记城市1为已访问
 * - 遍历城市1的邻居：城市0和城市3
 * - 城市0已访问，跳过
 * - 城市3未访问，检查边(1, 3)的标记为1，表示需要翻转，count + 1=2
 * - 递归调用dfs(3)：
 * - 标记城市3为已访问
 * - 遍历城市3的邻居：城市1和城市2
 * - 城市1已访问，跳过
 * - 城市2未访问，检查边(3, 2)的标记为0，表示不需要翻转
 * - 递归调用dfs(2)：
 * - 标记城市2为已访问
 * - 城市2没有未访问的邻居，返回
 * - 城市3没有未访问的邻居，返回
 * - 城市1没有未访问的邻居，返回
 * - 城市4未访问，检查边(0, 4)的标记为0，表示不需要翻转
 * - 递归调用dfs(4)：
 * - 标记城市4为已访问
 * - 遍历城市4的邻居：城市0和城市5
 * - 城市0已访问，跳过
 * - 城市5未访问，检查边(4, 5)的标记为1，表示需要翻转，count + 1=3
 * - 递归调用dfs(5)：
 * - 标记城市5为已访问
 * - 城市5没有未访问的邻居，返回
 * - 城市4没有未访问的邻居，返回
 * - 城市0没有未访问的邻居，返回
 * - 返回count=3
 *
 * 5. 关键点
 * - 数据结构选择：使用邻接表表示图，每个节点存储[邻居, 方向标记]的元组
 * - 算法思路：通过DFS / BFS遍历图，根据边的方向标记确定是否需要翻转
 * - 时间复杂度：O(n)，只需要遍历所有节点和边一次
 * - 空间复杂度：O(n)，需要存储图的结构和访问标记
 *
 * 6. 复杂度分析
 * - 时间复杂度：O(n)，其中n是城市数量，需要遍历所有节点和边
 * - 空间复杂度：O(n)，需要存储图的结构和访问标记
 *
 * 7. 方法选择
 * - 本题使用DFS / BFS都可以解决，DFS实现更简洁
 * - 关键是将有向图转换为无向图，并标记边的原始方向
 * - 通过比较遍历方向与原始方向确定是否需要翻转
 */

export function minReorder(n: number, connections: number[][]): number {
  // 构建邻接表
  const graph: [number, number][][] = Array(n)
    .fill(0)
    .map(() => []);

  // 添加双向边，并标记原始方向
  for (const [from, to] of connections) {
    graph[from].push([to, 1]); // 原始方向，需要翻转
    graph[to].push([from, 0]); // 反向连接，不需要翻转
  }

  // DFS遍历函数
  const visited: boolean[] = Array(n).fill(false);
  let count = 0;

  function dfs(city: number): void {
    visited[city] = true;

    for (const [neighbor, needReverse] of graph[city]) {
      if (!visited[neighbor]) {
        count += needReverse; // 如果是原方向，需要翻转
        dfs(neighbor);
      }
    }
  }

  dfs(0);
  return count;
}

export default {
  run: () => {
    const examples = [
      {
        input: [
          6,
          [
            [0, 1],
            [1, 3],
            [2, 3],
            [4, 0],
            [4, 5],
          ],
        ],
        output: 3,
      },
      // {
      //   input: [
      //     5,
      //     [
      //       [1, 0],
      //       [1, 2],
      //       [3, 2],
      //       [3, 4],
      //     ],
      //   ],
      //   output: 2,
      // },
      // {
      //   input: [
      //     3,
      //     [
      //       [1, 0],
      //       [2, 0],
      //     ],
      //   ],
      //   output: 0,
      // },
    ];

    for (const example of examples) {
      const [n, connections] = example.input as [number, number[][]];
      const result = minReorder(n, connections);
      console.log(`输入: n = ${n}, connections = ${JSON.stringify(connections)}`);
      console.log(`输出: ${result}`);
      console.log(`测试结果: ${result === example.output ? '通过' : '失败'}`);
      console.log('---');
    }
  },
};
